import { expect, test } from '@playwright/test'
import { installKomariFixture } from './fixtures/komari'

test('carrier hover preserves geometry and clears; light trails react to theme changes', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.clock.install({ time: new Date('2026-07-25T12:00:00Z') })
  await installKomariFixture(page, { preserveStorage: true, earthRenderer: 'cobe', earthArcMode: 'persistent', disablePageAnimation: false })
  await page.goto('/')
  const row = page.locator('[data-carrier-ping="unicom-latency"]').first()
  await row.scrollIntoViewIfNeeded()
  await page.mouse.move(0, 0)
  await expect(row).toHaveCSS('box-shadow', 'none')
  const box = await row.boundingBox()
  await row.hover()
  await expect(row).not.toHaveCSS('box-shadow', 'none')
  expect(await row.boundingBox()).toEqual(box)
  await page.screenshot({ path: 'test-results/carrier-hover.png' })
  await page.mouse.move(0, 0)
  await expect(row).toHaveCSS('box-shadow', 'none')
  await row.focus()
  await expect(row).not.toHaveCSS('box-shadow', 'none')
  const trails = page.locator('[data-earth-trails]')
  const body = trails.locator('stop[offset="0.55"]').first()
  const lightColor = await body.getAttribute('stop-color')
  await expect(trails.locator('path').first()).toHaveCSS('stroke-width', '2px')
  await page.getByRole('button', { name: '切换为深色主题（当前自动）', exact: true }).click()
  await expect(body).not.toHaveAttribute('stop-color', lightColor!)
  await expect(trails.locator('path').first()).toHaveCSS('stroke-width', '1.6px')
})
